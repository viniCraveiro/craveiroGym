// Generates integrations/exercise-names-pt.js: the catalogue's exercise names in Brazilian
// Portuguese (pt-BR over pt), for what the server writes itself, such as the Strava description
// (integrations/providers/strava.js). The API image cannot read catalogue/, so it gets this copy.
//   node scripts/build-exercise-names-pt.mjs           write it
//   node scripts/build-exercise-names-pt.mjs --check   fail when it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const i18n = path.join(here, '..', '..', 'catalogue', 'i18n');
const out = path.join(here, '..', 'integrations', 'exercise-names-pt.js');
const read = f => JSON.parse(fs.readFileSync(path.join(i18n, f), 'utf8'));
const names = {};
for (const pack of [read('pt.json'), read('pt-BR.json')]) {
  for (const [id, v] of Object.entries(pack)) if (v && typeof v.name === 'string' && v.name.trim()) names[id] = v.name.trim();
}
const sorted = Object.fromEntries(Object.keys(names).sort().map(k => [k, names[k]]));
const body = `/* GENERATED by scripts/build-exercise-names-pt.mjs from catalogue/i18n/pt.json and pt-BR.json — do not edit. */\nexport const NAMES_PT = ${JSON.stringify(sorted)};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== body) { console.error('integrations/exercise-names-pt.js is out of date: node scripts/build-exercise-names-pt.mjs'); process.exit(1); }
  console.log('exercise-names-pt.js is up to date');
} else {
  fs.writeFileSync(out, body);
  console.log(`${Object.keys(sorted).length} names written`);
}
